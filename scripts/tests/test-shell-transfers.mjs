import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';

const button = {}, notices = [], panes = [];
const document = { hidden: false, querySelector: () => button };
const window = { DengSecurityLock: { isLocked: () => false } };
const context = vm.createContext({ window, document, toast: text => notices.push(text), showPane: pane => panes.push(pane) });
vm.runInContext(readFileSync(new URL('../../web/js/shell-transfers.js', import.meta.url), 'utf8'), context);
const update = window.DevShellTransfers.update;
const task = { status: 'queued', total: 100, done: 0 };
update([task], false);
assert.equal(button.hidden, false);
assert.match(button.textContent, /等待上传/);
task.status = 'uploading'; task.done = 42;
update([task], false);
assert.match(button.textContent, /上传中 · 42%/);
task.done = 100; update([task], false);
assert.equal(notices.length, 0, 'byte progress alone must not announce success');
task.status = 'done'; update([task], false);
assert.equal(notices[0], '上传已完成');
assert.match(button.textContent, /上传已完成/);
update([task], false); update([task], false);
assert.equal(notices.length, 1, 'polling must not repeat a completion toast');
button.onclick(); assert.deepEqual(panes, ['transfers']);
update([task], true); assert.equal(button.hidden, true);
task.resultSeen = true; update([task], false); assert.equal(button.hidden, true);
update([{ status: 'done', historicalResult: true, resultSeen: true }], false);
assert.equal(notices.length, 1, 'history must remain quiet');
const failed = { status: 'failed' };
update([failed], false); assert.match(notices.at(-1), /上传失败/);
update([{ status: 'cancelled' }], false); assert.equal(button.hidden, true);
const hiddenCompletion = { status: 'done' };
document.hidden = true; update([hiddenCompletion], false);
assert.equal(hiddenCompletion.completionNotified, undefined);
document.hidden = false; update([hiddenCompletion], false);
assert.equal(hiddenCompletion.completionNotified, true);
console.log('PASS: shell upload progress, completion, failures, history and duplicate suppression');
