import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const source=readFileSync(new URL('../../web/js/app.js',import.meta.url),'utf8');
const start=source.indexOf('function startVerboseDiagnostics('), end=source.indexOf('\nfunction makeSessionState(',start);
assert(start>=0 && end>start);
const lines=[], timers=[], requests=[];
let round=0;
const state={id:'one',connected:true,closed:false,term:{writeln:line=>lines.push(line)}};
const context=vm.createContext({state,encodeURIComponent, setTimeout:fn=>timers.push(fn), api:async path=>{requests.push(path); round++; return {events:round===1?[{sequence:1,kind:'verbose-handshake',detail:'server=fixture',ageSeconds:0.25}]:round===2?[{sequence:2,kind:'verbose-monitor',detail:'system:exec-start',ageSeconds:1}]:[{sequence:3,kind:'verbose-transport-end',detail:'server-idle-timeout',ageSeconds:2}]};}});
vm.runInContext(source.slice(start,end),context);
context.startVerboseDiagnostics(state,3);
await new Promise(resolve=>setImmediate(resolve));
assert(lines.some(line=>line.includes('server=fixture')));
assert(requests[0].endsWith('after=0'));
timers.shift()(); await new Promise(resolve=>setImmediate(resolve));
assert(requests[1].endsWith('after=1'));
state.connected=false; timers.shift()(); await new Promise(resolve=>setImmediate(resolve));
assert(lines.some(line=>line.includes('server-idle-timeout')));
console.log('PASS: verbose SSH diagnostics appear in the terminal and continue after disconnect.');
